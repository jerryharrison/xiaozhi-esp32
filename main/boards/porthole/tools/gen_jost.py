#!/usr/bin/env python3
"""Generate porthole_jost.h: Jost glyphs (4-bit anti-aliased) for the Porthole's glance cards, at
the sizes of the approved browser prototype (packages/avatar-web/src/cards.ts, D = 466 px).

Usage (needs Pillow + fontTools with brotli; macOS /usr/bin/python3 has them), from main/boards/porthole:
  /usr/bin/python3 -E tools/gen_jost.py <skipper-ai>/packages/avatar-web/cards/public/jost.woff2 > porthole_jost.h

Jost is by the Jost Project Authors, SIL Open Font License 1.1 (variable font; weights picked
below). Non-ASCII characters map to control bytes (see EXTRA); card text is converted to that
encoding when a card arrives (CardUtf8ToFont in avatar_cards.h). The star is drawn here, since Jost
has no U+2605.
"""
import io, math, sys
from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

# control byte -> character (keep in sync with avatar_cards.h)
EXTRA = {1: "·", 2: "°", 3: "★", 4: "…", 5: "—", 6: "’", 7: "é"}
CHARS = "".join(chr(c) for c in range(32, 127)) + "".join(chr(k) for k in sorted(EXTRA))

FONTS = [
    # name, pixel size, weight      prototype size (fraction of D)
    ("title", 34, 400),            # 0.074: card titles
    ("call", 44, 450),             # 0.094: a caller's name
    ("msg", 28, 400),              # 0.060: message lines, titles under a label
    ("body", 24, 400),             # 0.052: detail lines
    ("label", 17, 500),            # 0.036: spaced capitals above the title
    ("small", 16, 400),            # 0.035: hints ("tap to hear")
]


def load(path, size, weight):
    f = TTFont(path)
    f.flavor = None
    buf = io.BytesIO()
    f.save(buf)
    buf.seek(0)
    font = ImageFont.truetype(buf, size)
    try:
        font.set_variation_by_axes([weight])
    except Exception:
        pass
    return font


def star_bitmap(font, size):
    """A five-point star about the height of a capital, on the baseline."""
    ascent, _ = font.getmetrics()
    cap = font.getbbox("H")
    h = cap[3] - cap[1]
    w = h
    s = 4  # supersample
    img = Image.new("L", (w * s, h * s), 0)
    cx, cy, ro, ri = w * s / 2, h * s * 0.55, h * s * 0.55, h * s * 0.22
    pts = []
    for i in range(10):
        a = -math.pi / 2 + i * math.pi / 5
        r = ro if i % 2 == 0 else ri
        pts.append((cx + r * math.cos(a), cy + r * math.sin(a)))
    ImageDraw.Draw(img).polygon(pts, fill=255)
    img = img.resize((w, h), Image.LANCZOS)
    return round(h * 1.15), 1, cap[1], w, h, list(img.getdata())


def glyphs(path, size, weight):
    font = load(path, size, weight)
    ascent, descent = font.getmetrics()
    out = []
    for c in CHARS:
        ch = EXTRA.get(ord(c), c)
        if ch == "★":
            adv, xo, yo, w, h, px = star_bitmap(font, size)
        else:
            adv = round(font.getlength(ch))
            box = font.getbbox(ch)
            w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
            xo, yo = box[0], box[1]
            px = []
            if w and h:
                img = Image.new("L", (w, h), 0)
                ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
                px = list(img.getdata())
        bits = []
        for i in range(0, len(px), 2):
            a = px[i] >> 4
            b = (px[i + 1] >> 4) if i + 1 < len(px) else 0
            bits.append((a << 4) | b)
        out.append((adv, xo, yo, w, h, bits))
    return out, ascent, ascent + descent


def cstr(s):
    out = ""
    for c in s:
        o = ord(c)
        if c in '\\"':
            out += "\\" + c
        elif o < 32:
            out += '\\x%02x""' % o   # split the literal so the next char isn't read as hex
        else:
            out += c
    return '"' + out + '"'


def main():
    path = sys.argv[1]
    print("/* GENERATED by tools/gen_jost.py from Jost (The Jost Project Authors, SIL OFL 1.1). Do not edit. */")
    print("#pragma once")
    print('#include "porthole_font.h"\n')
    for name, size, weight in FONTS:
        gl, ascent, line_h = glyphs(path, size, weight)
        bmp, entries, off = [], [], 0
        for adv, xo, yo, w, h, bits in gl:
            entries.append(f"{{{off},{w},{h},{xo},{yo},{adv}}}")
            bmp += bits
            off += len(bits)
        print(f"static const uint8_t jf_{name}_bitmap[{max(1, len(bmp))}] = {{")
        for i in range(0, len(bmp), 24):
            print("  " + ",".join(str(b) for b in bmp[i:i + 24]) + ",")
        print("};")
        print(f"static const pf_glyph_t jf_{name}_glyphs[{len(entries)}] = {{")
        for i in range(0, len(entries), 6):
            print("  " + ",".join(entries[i:i + 6]) + ",")
        print("};")
        print(f"static const pf_font_t jf_{name} = {{ {cstr(CHARS)}, jf_{name}_glyphs, jf_{name}_bitmap, {len(entries)}, {ascent}, {line_h} }};\n")


if __name__ == "__main__":
    main()
