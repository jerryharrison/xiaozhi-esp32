#!/usr/bin/env python3
"""Generate porthole_font.h: anti-aliased 4-bit glyph bitmaps for the Porthole's text overlay.

Usage (needs Pillow; macOS /usr/bin/python3 has it), from main/boards/porthole:
  python3 -E tools/gen_font.py <Montserrat-Medium.ttf> > porthole_font.h

The TTF is Montserrat (SIL Open Font License), shipped with LVGL at
managed_components/lvgl__lvgl/scripts/built_in_font/Montserrat-Medium.ttf.
"""
import sys
from PIL import Image, ImageDraw, ImageFont

FONTS = [
    # name, pixel size, characters
    ("text", 26, "".join(chr(c) for c in range(32, 127))),
    ("big", 84, "0123456789%"),
]


def glyphs(ttf, size, chars):
    font = ImageFont.truetype(ttf, size)
    ascent, descent = font.getmetrics()
    out = []
    for ch in chars:
        adv = round(font.getlength(ch))
        box = font.getbbox(ch)  # relative to the origin at the top of the ascent
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        bits = []
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
            px = list(img.getdata())
            for i in range(0, len(px), 2):
                a = px[i] >> 4
                b = (px[i + 1] >> 4) if i + 1 < len(px) else 0
                bits.append((a << 4) | b)
        out.append((ch, adv, box[0], box[1], w, h, bits))
    return out, ascent, ascent + descent


def main():
    ttf = sys.argv[1]
    print("/* GENERATED by tools/gen_font.py from Montserrat-Medium (SIL OFL 1.1). Do not edit. */")
    print("#pragma once")
    print("#include <stdint.h>\n")
    print("typedef struct { uint32_t off; uint8_t w, h; int8_t xo, yo; uint8_t adv; } pf_glyph_t;")
    print("typedef struct { const char* chars; const pf_glyph_t* glyphs; const uint8_t* bitmap; uint8_t count, ascent, line_h; } pf_font_t;\n")
    for name, size, chars in FONTS:
        gl, ascent, line_h = glyphs(ttf, size, chars)
        bmp, entries, off = [], [], 0
        for ch, adv, xo, yo, w, h, bits in gl:
            entries.append(f"{{{off},{w},{h},{xo},{yo},{adv}}}")
            bmp += bits
            off += len(bits)
        esc = chars.replace("\\", "\\\\").replace('"', '\\"')
        print(f"static const uint8_t pf_{name}_bitmap[{max(1, len(bmp))}] = {{")
        for i in range(0, len(bmp), 24):
            print("  " + ",".join(str(b) for b in bmp[i:i + 24]) + ",")
        print("};")
        print(f"static const pf_glyph_t pf_{name}_glyphs[{len(entries)}] = {{")
        for i in range(0, len(entries), 6):
            print("  " + ",".join(entries[i:i + 6]) + ",")
        print("};")
        print(f'static const pf_font_t pf_{name} = {{ "{esc}", pf_{name}_glyphs, pf_{name}_bitmap, {len(entries)}, {ascent}, {line_h} }};\n')


if __name__ == "__main__":
    main()
